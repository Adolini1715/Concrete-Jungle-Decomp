XBBasePixelShader XBPixelShader;

XBBasePixelShader::XBBasePixelShader()
{
    m_pDefs[0] = 0;
    m_pDefs[1] = dwPs_focusblurPixelShader;
    m_pDefs[2] = dwPs_alphafogPixelShader;
    m_pDefs[3] = dwPs_negativePixelShader;
    m_pDefs[4] = dwPs_enhancePixelShader;
    m_pDefs[5] = dwPs_BloomMaskPixelShader;
    m_pDefs[6] = dwPs_BaseLightShadowPixelShader;
    m_pDefs[7] = dwPs_ShadowMapWithIdPixelShader;
}

void XBBasePixelShader::DeclareAllPixelShaders()
{
    for (unsigned int i = 0; i < 8; i++)
        if (m_pDefs[i]) xb::D3DDevice::CreatePixelShader((const xb::_D3DPixelShaderDef *)m_pDefs[i], &m_Handles[i]);
}
